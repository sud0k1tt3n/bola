SETTLEMENTS = [dict(zip(("name", "kind", "region", "lat", "lon"), s)) for s in SEED]


def _norm(value: str) -> str:
    return "".join(ch for ch in value.lower().replace("ё", "е") if ch.isalnum())


def search(query: str, limit: int = 8) -> list[dict]:
    """Префикс > подстрока > регион > похожее написание (опечатки)."""
    needle = _norm(query)
    if len(needle) < 2:
        return []
    scored = []
    for item in SETTLEMENTS:
        name, region = _norm(item["name"]), _norm(item["region"])
        if name.startswith(needle):
            score = 0.0
        elif needle in name:
            score = 0.3
        elif needle in region:
            score = 0.6
        else:
            ratio = SequenceMatcher(None, needle, name[: len(needle) + 2]).ratio()
            if ratio < 0.7:
                continue
            score = 1.0 - ratio + 0.7
        scored.append((score, item["name"], item))
    scored.sort(key=lambda t: (t[0], t[1]))
    return [t[2] for t in scored[:limit]]


def _distance_km(lat1, lon1, lat2, lon2) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


_DIRS = ["С", "СВ", "В", "ЮВ", "Ю", "ЮЗ", "З", "СЗ"]


def describe(lat: float, lon: float, max_km: float = 150) -> Optional[str]:
    """«12 км к ЮВ от Каширы»-подобная подпись по ближайшему пункту справочника."""
    best = min(SETTLEMENTS, key=lambda s: _distance_km(lat, lon, s["lat"], s["lon"]))
    d = _distance_km(lat, lon, best["lat"], best["lon"])
    if d > max_km:
        return None
    if d < 1:
        return f"{best['name']}, {best['region']}"
    y = math.sin(math.radians(lon - best["lon"])) * math.cos(math.radians(lat))
    x = (math.cos(math.radians(best["lat"])) * math.sin(math.radians(lat))
         - math.sin(math.radians(best["lat"])) * math.cos(math.radians(lat)) * math.cos(math.radians(lon - best["lon"])))
    bearing = (math.degrees(math.atan2(y, x)) + 360) % 360
    direction = _DIRS[int((bearing + 22.5) // 45) % 8]
    abbr = {"город": "г.", "посёлок": "пос.", "село": "с."}.get(best["kind"], "")
    return f"{d:.0f} км к {direction} от {abbr} {best['name']} ({best['region']})"
